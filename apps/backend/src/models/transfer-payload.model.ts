// 매핑 엔터티 없음(비저장) — 복호화 원문은 어떤 저장소에도 남기지 않는다(DATA-001-02·DATA-001-03).

/**
 * 복호화(FN-004)로 복원되는 전달 데이터. 허브가 해석하는 필드는 `trackingKey` 하나뿐이며,
 * 그 밖의 필드는 발송처가 자유롭게 정의하는 업무 필드다 — 허브는 이를 검증·해석하지 않고
 * 그대로 수신처 전달 페이로드로 삼는다(`BIZ-004-05`·`DATA-004-01`).
 *
 * 지역 변수로만 다루고 전역 상태·요청 컨텍스트 저장소에 넣지 않는다. 본인확인 단계에서는
 * `trackingKey` 만 취한 뒤 즉시 폐기하고, 승인 시점에 다시 복호화해 얻는다(`BIZ-002-06`).
 * 나머지 필드는 열린 형태로 둔다 — 발송처가 필드를 늘려도 허브를 고치지 않아야 한다.
 */
export interface TransferPayload {
  trackingKey: string;
  [field: string]: unknown;
}
